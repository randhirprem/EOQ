const demoPassword=require('node:crypto').randomBytes(24).toString('base64url');
const {chromium}=require('playwright');
const fs=require('fs'),http=require('http'),assert=require('node:assert/strict');
fs.mkdirSync('/tmp/stockwise-models',{recursive:true});
(async()=>{
 const server=http.createServer((req,res)=>{res.setHeader('Content-Type','text/html');res.end(fs.readFileSync(require('path').join(__dirname,'../index.html')));}).listen(8876,'127.0.0.1');
 const browser=await chromium.launch({headless:true,...(process.env.CHROME_BIN?{executablePath:process.env.CHROME_BIN}:{})});
 const errors=[];
 const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
 page.on('pageerror',e=>{errors.push(e.message);console.log('PAGE ERROR',e.message);});
 page.on('console',m=>{if(m.type()==='error')console.log('CONSOLE ERROR',m.text().slice(0,200));});
 try{
 await page.goto('http://127.0.0.1:8876');
 await page.locator('#show-signup').click();
 await page.locator('#account-name').fill('Model Tester');
 await page.locator('#account-email').fill('model-test@example.com');
 await page.locator('#account-password').fill(demoPassword);
 await page.locator('#account-confirm').fill(demoPassword);
 await page.locator('#auth-submit').click();
 await page.locator('#tab-forecast').click();
 await page.locator('#sample-data').click();
 await page.waitForFunction(()=>!document.querySelector('#cancel-model').hidden,{},{timeout:15000});
 await page.waitForFunction(()=>document.querySelector('#cancel-model').hidden,{},{timeout:150000});
 console.log('LINEAR STATUS',await page.locator('#model-status').textContent());
 assert.match(await page.locator('#model-status').textContent(),/fitted/);
 console.log('LINEAR METRICS',await page.locator('#diagnostic-metrics').textContent());
 await page.screenshot({path:'/tmp/stockwise-models/desktop.png',fullPage:true});
 await page.locator('#model-type').selectOption('arima');
 await page.locator('#model-d').fill('1');await page.locator('#model-d').dispatchEvent('change');
 await page.locator('#fit-model').click();
 await page.waitForFunction(()=>document.querySelector('#cancel-model').hidden,{},{timeout:150000});
 console.log('ARIMA STATUS',await page.locator('#model-status').textContent());assert.match(await page.locator('#model-status').textContent(),/fitted/);
 await page.locator('#model-type').selectOption('sarima');
 await page.locator('#model-d').fill('0');await page.locator('#model-d').dispatchEvent('change');
 await page.locator('#model-P').fill('1');await page.locator('#model-P').dispatchEvent('change');
 await page.locator('#fit-model').click();
 await page.waitForFunction(()=>document.querySelector('#cancel-model').hidden,{},{timeout:150000});
 console.log('SARIMA STATUS',await page.locator('#model-status').textContent());assert.match(await page.locator('#model-status').textContent(),/fitted/);
 await page.screenshot({path:'/tmp/stockwise-models/sarima.png',fullPage:true});
 if(await page.locator('#diagnostics').isVisible()){
 const download=page.waitForEvent('download');await page.locator('#generate-report').click();await (await download).saveAs('/tmp/stockwise-models/report.pdf');console.log('PDF DOWNLOADED');
 }
 await page.locator('#stationarity-assist').click();
 await page.waitForFunction(()=>document.querySelector('#cancel-model').hidden,{},{timeout:150000});
 console.log('STATIONARITY',await page.locator('#model-status').textContent());
 await page.setViewportSize({width:390,height:844});await page.waitForFunction(()=>document.documentElement.scrollWidth<=innerWidth);await page.screenshot({path:'/tmp/stockwise-models/mobile.png',fullPage:true});
 console.log('OVERFLOW',await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth));
 assert.equal(await page.locator('#use-forecast').isDisabled(),true);
 await page.locator('#model-P').fill('');await page.locator('#model-P').dispatchEvent('change');
 await page.locator('#model-type').selectOption('linear');
 await page.locator('#fit-model').click();
 await page.waitForFunction(()=>document.querySelector('#cancel-model').hidden,{},{timeout:150000});
 assert.match(await page.locator('#model-status').textContent(),/fitted/);
 await page.locator('#use-forecast').click();
 assert.equal(await page.locator('#view-eoq').isVisible(),true);
 assert.ok(Number(await page.locator('#demand').inputValue())>0);
 await page.locator('#currency').selectOption('SGD');
 assert.match(await page.locator('#cost-value').textContent(),/S\$/);
 await page.locator('#tab-forecast').click();
 await page.evaluate(()=>{document.querySelector('#fit-model').click();document.querySelector('#cancel-model').click();});
 assert.match(await page.locator('#model-status').textContent(),/cancelled/);
 assert.equal(await page.locator('#use-forecast').isDisabled(),true);
 await page.locator('#model-type').selectOption('sarima');
 await page.locator('#model-P').fill('0');await page.locator('#model-P').dispatchEvent('change');
 const shortCSV='Date,Quantity\n'+Array.from({length:12},(_,i)=>`2025-${String(i+1).padStart(2,'0')}-15,${100+i}`).join('\n');
 await page.locator('#file-input').setInputFiles({name:'short.csv',mimeType:'text/csv',buffer:Buffer.from(shortCSV)});
 await page.waitForFunction(()=>document.querySelector('#model-status').textContent.includes('three full seasons'),{},{timeout:150000});
 assert.equal(await page.locator('#diagnostics').isVisible(),false);
 assert.equal(await page.locator('#use-forecast').isDisabled(),true);
 assert.deepEqual(errors,[]);
 console.log('PASS: all models, PDF, stationarity, mobile, hidden settings, EOQ/SGD transfer, cancellation, short-history rejection.');
 }finally{await browser.close();server.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
